// Generates lib/src/generated/pindoro_tokens.dart from tokens/tokens.json (the
// claude.ai design system, copied verbatim) and tokens/app.json (app-only).
// Run from anywhere: `dart run packages/pindoro_design/tool/generate_tokens.dart`.
import 'dart:convert';
import 'dart:io';

void main() {
  final packageDir = File.fromUri(Platform.script).parent.parent;
  Map<String, Object?> read(String name) =>
      jsonDecode(File('${packageDir.path}/tokens/$name').readAsStringSync())
          as Map<String, Object?>;
  final system = read('tokens.json');
  final tokens = collectTokens([system, read('app.json')]);

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_tokens.dart from tokens/*.json.')
    ..writeln('// DO NOT EDIT. Edit the json and run `just gen`.')
    ..writeln()
    ..writeln("import 'package:flutter/animation.dart';")
    ..writeln("import 'package:flutter/painting.dart';")
    ..writeln()
    ..write(generateDart(tokens, system['type']! as Map<String, Object?>));

  final outFile = File(
    '${packageDir.path}/lib/src/generated/pindoro_tokens.dart',
  )..createSync(recursive: true);
  outFile.writeAsStringSync(out.toString());
  final format = Process.runSync(Platform.resolvedExecutable, [
    'format',
    outFile.path,
  ]);
  if (format.exitCode != 0) {
    throw ProcessException('dart', ['format'], '${format.stderr}');
  }
  stdout.writeln('Wrote ${outFile.path}');
}

/// Every `{name, value}` from each top-level group's `tokens` list.
Map<String, Object> collectTokens(List<Map<String, Object?>> files) {
  final tokens = <String, Object>{};
  for (final group in files.expand((f) => f.values)) {
    if (group case {'tokens': final List<Object?> list}) {
      for (final token in list.cast<Map<String, Object?>>()) {
        final name = token['name']! as String;
        final value = token['value']!;
        if (tokens.containsKey(name)) {
          throw FormatException(
            'Duplicate token "$name": drop it from app.json',
          );
        }
        tokens[name] = value;
      }
    }
  }
  return tokens;
}

/// The value of [name] in [theme], following `{other.token}` aliases.
String resolve(Map<String, Object> tokens, String name, String theme) {
  final value = tokens[name] ?? (throw FormatException('Unknown "$name"'));
  final raw = (value is Map ? value[theme] : value)! as String;
  final alias = RegExp(r'^\{(.+)\}$').firstMatch(raw);
  return alias == null ? raw : resolve(tokens, alias[1]!, theme);
}

String generateDart(Map<String, Object> tokens, Map<String, Object?> type) {
  final palette = <String>[];
  final themed = <String, Map<String, String>>{};
  final classes = <String, List<String>>{};

  for (final MapEntry(key: name, :value) in tokens.entries) {
    final [prefix, ...rest] = name.split('.');
    if (prefix == 'color') {
      final field = _camel(rest);
      if (value is String) {
        palette.add('static const Color $field = ${_color(value)};');
      } else {
        themed[field] = {
          for (final t in ['light', 'dark'])
            t: _color(resolve(tokens, name, t)),
        };
      }
      continue;
    }
    var member = _camel(rest);
    if (member.startsWith(RegExp('[0-9]'))) member = '${prefix[0]}$member';
    final members = classes.putIfAbsent('Pindoro${_pascal(prefix)}', () => []);
    for (final (suffix, raw) in switch (value) {
      String v => [('', v)],
      {'light': String l, 'dark': String d} => [('Light', l), ('Dark', d)],
      _ => throw FormatException('Unsupported token "$name": $value'),
    }) {
      if (_constant(raw) case (final type, final code)) {
        members.add('static const $type $member$suffix = $code;');
      }
    }
  }

  final fields = themed.keys;
  final out = StringBuffer()
    ..writeln('abstract final class PindoroPalette {')
    ..writeAll(palette, '\n')
    ..writeln('}')
    ..writeln()
    ..writeln('/// Semantic, game and component colours per theme.')
    ..writeln('final class PindoroColors {')
    ..writeln('const PindoroColors({')
    ..writeAll(fields.map((f) => 'required this.$f,'), '\n')
    ..writeln('});')
    ..writeAll(fields.map((f) => 'final Color $f;'), '\n')
    ..writeln();
  for (final theme in ['light', 'dark']) {
    out
      ..writeln('static const $theme = PindoroColors(')
      ..writeAll(fields.map((f) => '$f: ${themed[f]![theme]},'), '\n')
      ..writeln(');');
  }
  out
    ..writeln(
      'static PindoroColors lerp(PindoroColors a, PindoroColors b, double t) =>',
    )
    ..writeln('PindoroColors(')
    ..writeAll(fields.map((f) => '$f: Color.lerp(a.$f, b.$f, t)!,'), '\n')
    ..writeln(');')
    ..writeln('}');
  for (final MapEntry(key: name, value: members) in classes.entries) {
    out
      ..writeln()
      ..writeln('abstract final class $name {')
      ..writeAll(members, '\n')
      ..writeln('}');
  }
  return (out
        ..writeln()
        ..write(_typeClass(type)))
      .toString();
}

/// One TextStyle per type role. Every role gets tabular figures so scores,
/// distances and timers never jitter, wherever they appear.
String _typeClass(Map<String, Object?> type) {
  final family = ((type['fonts']! as List).first as Map)['family'];
  final out = StringBuffer()
    ..writeln('abstract final class PindoroType {')
    ..writeln("static const String family = '$family';")
    ..writeln("static const String package = 'pindoro_design';")
    ..writeln(
      'static const List<FontFeature> tabularFigures = '
      '[FontFeature.tabularFigures()];',
    );
  for (final group in (type['groups']! as List).cast<Map<String, Object?>>()) {
    for (final s in (group['styles']! as List).cast<Map<String, Object?>>()) {
      final size = _px(s['fontSize']! as String);
      out.writeln(
        'static const TextStyle ${_camel((s['name']! as String).split('.'))} = '
        'TextStyle(fontFamily: family, package: package, fontSize: $size, '
        'height: ${_px(s['lineHeight']! as String)} / $size, '
        'fontWeight: FontWeight.w${s['fontWeight']}, '
        'letterSpacing: ${_px(s['letterSpacing']! as String)}, '
        'fontFeatures: tabularFigures);',
      );
    }
  }
  return (out..writeln('}')).toString();
}

/// Dart type and constant for a non-colour token value; null for `none`.
(String, String)? _constant(String v) {
  final number = r'-?\d+(?:\.\d+)?';
  if (RegExp('^$number(px)?\$').hasMatch(v)) return ('double', _px(v));
  if (RegExp(r'^(\d+)ms$').firstMatch(v) case final m?) {
    return ('Duration', 'Duration(milliseconds: ${m[1]})');
  }
  if (RegExp(r'^cubic-bezier\((.+)\)$').firstMatch(v) case final m?) {
    return ('Curve', 'Cubic(${m[1]})');
  }
  if (v == 'linear') return ('Curve', 'Curves.linear');
  if (RegExp(
        '^mass ($number) stiffness ($number) damping ($number)\$',
      ).firstMatch(v)
      case final m?) {
    return (
      'SpringDescription',
      'SpringDescription(mass: ${m[1]}, stiffness: ${m[2]}, damping: ${m[3]})',
    );
  }
  final shadow = RegExp(
    '^($number)(?:px)? ($number)(?:px)? ($number)(?:px)? '
    r'rgba\((\d+), (\d+), (\d+), ([\d.]+)\)$',
  ).firstMatch(v);
  if (shadow != null) {
    final [x, y, blur, r, g, b, a] = [for (var i = 1; i <= 7; i++) shadow[i]!];
    return (
      'BoxShadow',
      'BoxShadow(color: Color.fromRGBO($r, $g, $b, $a), '
          'offset: Offset($x, $y), blurRadius: $blur)',
    );
  }
  if (v == 'none') return null;
  throw FormatException('Unsupported token value: $v');
}

String _px(String v) => v.replaceFirst(RegExp(r'px$'), '');

/// `street-card.bg` → `streetCardBg`.
String _camel(List<String> parts) {
  final words = parts.expand((p) => p.split('-')).toList();
  return words.first + words.skip(1).map(_capitalise).join();
}

String _pascal(String word) => _capitalise(_camel([word]));

String _capitalise(String w) => w[0].toUpperCase() + w.substring(1);

/// CSS `#RRGGBB` / `#RRGGBBAA` → Dart `Color(0xAARRGGBB)`.
String _color(String hex) {
  final d = hex.substring(1).toUpperCase();
  return switch (d.length) {
    6 => 'Color(0xFF$d)',
    8 => 'Color(0x${d.substring(6)}${d.substring(0, 6)})',
    _ => throw FormatException('Bad colour: $hex'),
  };
}
